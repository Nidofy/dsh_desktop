import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,readdir} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {migrateWorkspaceHistory,mergeWorkspaces} from '../runtime-src/workspace-migration.mjs';
await mkdir('.build',{recursive:true});
const root=await mkdtemp(resolve('.build/workspace-migration-')),home=join(root,'dsh');
const first=join(root,'profiles','p-'+'a'.repeat(32),'dsh'),second=join(root,'profiles','p-'+'b'.repeat(32),'dsh');
const put=async(base,path,value)=>{await mkdir(join(base,path,'..'),{recursive:true});await writeFile(join(base,path),typeof value==='string'?value:JSON.stringify(value));};
const workspace=(id)=>({unit:{name:'workspace',version:2},global:{initialized:true,workspaceIds:[id],archivedSessionIds:['archived-'+id]},tables:{workspaces:{[id]:{id,path:'D:/synthetic/'+id}}}});
await put(home,'storages/workspace.json',workspace('shared'));
await put(first,'storages/workspace.json',workspace('one'));
await put(second,'storages/workspace.json',workspace('two'));
await put(first,'sessions/project/session-a/session.v3.jsonl.zstd','synthetic opaque session bytes A');
await put(second,'sessions/project/session-b/session.v3.jsonl','synthetic session B');
await put(first,'attachments/v1/image.png','synthetic image');
await put(first,'settings.yaml','ui-theme:\n  preference: dark\n');
assert.equal((await migrateWorkspaceHistory({root,home})).migrated,2);
const result=JSON.parse(await readFile(join(home,'storages/workspace.json'),'utf8'));
assert.deepEqual(result.global.workspaceIds,['shared','one','two']);
assert.deepEqual(result.global.archivedSessionIds,['archived-shared','archived-one','archived-two']);
assert.equal(await readFile(join(home,'sessions/project/session-a/session.v3.jsonl.zstd'),'utf8'),'synthetic opaque session bytes A');
assert.equal(await readFile(join(first,'sessions/project/session-a/session.v3.jsonl.zstd'),'utf8'),'synthetic opaque session bytes A');
assert.equal(await readFile(join(home,'settings.yaml'),'utf8'),'ui-theme:\n  preference: dark\n');
assert.equal((await migrateWorkspaceHistory({root,home})).migrated,0);
await put(home,'sessions/project/session-a/session.v3.jsonl.zstd','new task after migration');
await migrateWorkspaceHistory({root,home});
assert.equal(await readFile(join(home,'sessions/project/session-a/session.v3.jsonl.zstd'),'utf8'),'new task after migration','completed imports never overwrite new work');
const third=join(root,'profiles','p-'+'c'.repeat(32),'dsh');
await put(third,'sessions/project/session-b/session.v3.jsonl','conflicting history');
await put(third,'sessions/project/new/session.v3.jsonl','should not copy on conflict');
await assert.rejects(migrateWorkspaceHistory({root,home}),/conflicts/);
assert.equal(await readFile(join(home,'sessions/project/session-b/session.v3.jsonl'),'utf8'),'synthetic session B');
await assert.rejects(readFile(join(home,'sessions/project/new/session.v3.jsonl')),error=>error.code==='ENOENT');
await assert.rejects(migrateWorkspaceHistory({root,home:first}),/mismatch/);
console.log('PASS workspace migration: merged history, attachments and workspace lists; original data retained; collision refusal and restart idempotence');
console.log('Evidence:',root);

const duplicateRoot=await mkdtemp(resolve('.build/workspace-duplicates-')),duplicateHome=join(duplicateRoot,'dsh');
const oldProfile=join(duplicateRoot,'profiles','p-'+'a'.repeat(32),'dsh');
const a=workspace('keep'),b=workspace('old');
a.tables.workspaces.keep.sessionIds=['session-shared','session-current'];
b.tables.workspaces.old.path=a.tables.workspaces.keep.path;
b.tables.workspaces.old.sessionIds=['session-old','session-shared'];
a.tables.workspaces.keep.title='Current title';
b.tables.workspaces.old.title='Old title';
const combined=mergeWorkspaces(a,b);
assert.deepEqual(combined.global.workspaceIds,['keep']);
assert.deepEqual(combined.tables.workspaces.keep.sessionIds,['session-shared','session-current','session-old']);
assert.equal(combined.tables.workspaces.keep.title,'Current title');
assert.deepEqual(combined.global.archivedSessionIds,['archived-keep','archived-old']);
const sameId=structuredClone(a);sameId.tables.workspaces.keep.sessionIds=['another-session'];
assert.deepEqual(mergeWorkspaces(a,sameId).tables.workspaces.keep.sessionIds,['session-shared','session-current','another-session']);
sameId.tables.workspaces.keep.path='D:/different-path';
assert.throws(()=>mergeWorkspaces(a,sameId),/different paths/);
const damaged=structuredClone(a);Object.assign(damaged.tables.workspaces,b.tables.workspaces);damaged.global.workspaceIds.push('old');
damaged.global.archivedSessionIds.push('archived-old');
const original=JSON.stringify(damaged,null,2);
await put(duplicateHome,'storages/workspace.json',original);
await put(duplicateHome,'desktop-workspace-migration.json',{version:1,completed:['p-'+'a'.repeat(32)]});
await put(oldProfile,'storages/workspace.json',b);
await put(duplicateHome,'sessions/sentinel.txt','unchanged history');
assert.deepEqual(await migrateWorkspaceHistory({root:duplicateRoot,home:duplicateHome}),{migrated:0,repaired:1});
assert.deepEqual(JSON.parse(await readFile(join(duplicateHome,'storages/workspace.json'),'utf8')),combined);
const backupDir=join(duplicateHome,'desktop-workspace-repairs');
const backups=await readdir(backupDir);assert.equal(backups.length,1);
assert.equal(await readFile(join(backupDir,backups[0]),'utf8'),original);
assert.equal(await readFile(join(duplicateHome,'sessions/sentinel.txt'),'utf8'),'unchanged history');
assert.deepEqual(await migrateWorkspaceHistory({root:duplicateRoot,home:duplicateHome}),{migrated:0,repaired:0});
assert.equal((await readdir(backupDir)).length,1);
const noProfiles=await mkdtemp(resolve('.build/workspace-duplicates-no-profiles-'));
await put(join(noProfiles,'dsh'),'storages/workspace.json',damaged);
assert.equal((await migrateWorkspaceHistory({root:noProfiles,home:join(noProfiles,'dsh')})).repaired,1);
const pending=structuredClone(damaged);pending.global.pendingMutation={operation:'delete',workspaceId:'old'};
assert.throws(()=>mergeWorkspaces(null,pending),/mutation must recover/);
console.log('PASS same-directory identity merge, session union, completed migration repair, exact backup, idempotence and ambiguous identity refusal');

// A completed repair is not silently rerun on later user data. The explicit
// stopped-engine repair entry still retains the exact new damaged document.
await put(duplicateHome,'storages/workspace.json',original);
assert.equal((await migrateWorkspaceHistory({root:duplicateRoot,home:duplicateHome})).repaired,0);
assert.equal(await readFile(join(duplicateHome,'storages/workspace.json'),'utf8'),original);
assert.equal((await migrateWorkspaceHistory({root:duplicateRoot,home:duplicateHome,repairDuplicates:true})).repaired,1);
for(const incoming of [false,true]){
  const r=await mkdtemp(resolve('.build/workspace-unknown-')),h=join(r,'dsh');
  await put(h,'storages/workspace.json',incoming?damaged:{...damaged,unit:{name:'workspace',version:99}});
  if(incoming)await put(join(r,'profiles','p-'+'d'.repeat(32),'dsh'),'storages/workspace.json',{...damaged,unit:{name:'workspace',version:99}});
  const bytes=await readFile(join(h,'storages/workspace.json'));
  await assert.rejects(migrateWorkspaceHistory({root:r,home:h}),e=>e.code==='WORKSPACE_VERSION_UNSUPPORTED');
  assert.deepEqual(await readFile(join(h,'storages/workspace.json')),bytes);
  assert.deepEqual((await readdir(h)).sort(),['storages'],'future format must not publish a repair, backup or checkpoint');
}
console.log('PASS migration version bounds: future shared/source formats byte-identical; repair once and explicit repair');
