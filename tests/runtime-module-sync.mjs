import assert from 'node:assert/strict';
import {mkdir,mkdtemp,readFile,readdir,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {syncRootModules} from '../scripts/runtime-module-sync.mjs';
await mkdir('.build',{recursive:true});
const root=await mkdtemp(resolve('.build/module-sync-')),source=join(root,'source'),target=join(root,'runtime');
await mkdir(source);await mkdir(target);
await writeFile(join(source,'host.mjs'),'new host');
await writeFile(join(target,'host.mjs'),'old host');
await writeFile(join(target,'removed.mjs'),'removed module');
await writeFile(join(target,'node.exe'),'preserved runtime');
await mkdir(join(target,'dsh'));
await writeFile(join(target,'dsh','upstream.mjs'),'preserved upstream');
await syncRootModules(source,target);
assert.deepEqual((await readdir(target)).sort(),['dsh','host.mjs','node.exe']);
assert.equal(await readFile(join(target,'host.mjs'),'utf8'),'new host');
assert.equal(await readFile(join(target,'dsh','upstream.mjs'),'utf8'),'preserved upstream');
await syncRootModules(source,target);
await mkdir(join(target,'unexpected.mjs'));
await assert.rejects(syncRootModules(source,target),/regular files/);
console.log('PASS runtime module staging: stale modules removed, native/upstream retained, idempotence, non-files rejected');
