import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {NotificationFeed,installNotifications} from '../runtime-src/desktop-notifications.mjs';
let now=10000;
const feed=new NotificationFeed(()=>now),session={header:{id:'task-a'}};
let seq=0;
const event=(type,data={},target=session)=>feed.event(target,{type,data,seq:seq++,time:now});
event('turn/start');event('approval/asked',{id:'p',reason:'PRIVATE_REASON'});
const first=feed.snapshot();assert.equal(first.items[0].kind,'permission');
assert(!JSON.stringify(first).includes('PRIVATE'));assert(!('pendingId' in first.items[0]));
feed.event(session,{type:'approval/asked',data:{id:'p'},seq:seq-1});
assert.equal(feed.snapshot().items.length,1,'duplicate committed event does not notify twice');
event('approval/decided',{id:'p'});assert.equal(feed.snapshot().items.length,0,'resolved approvals cannot surface on next native poll');
event('tool/call',{name:'ask_user_question',callId:'q',arguments:'PRIVATE_QUESTION'});
assert.equal(feed.snapshot().items[0].kind,'input');
event('tool/result',{message:{content:[{toolCallId:'q',text:'PRIVATE_ANSWER'}]}});assert.equal(feed.snapshot().items.length,0);
event('turn/end',{reason:{kind:'completed'}});assert.equal(feed.snapshot().items[0].kind,'completed');
const end=feed.snapshot();assert.equal(feed.snapshot(end.revision).items.length,0,'cursor consumes once');
event('turn/start');assert.equal(feed.snapshot().items.length,0,'a new turn retires previous result');
event('turn/end',{reason:{kind:'error',message:'PRIVATE_ERROR'}});assert.equal(feed.snapshot().items[0].kind,'failed');
event('turn/end',{reason:{kind:'aborted'}});assert.equal(feed.snapshot().items.length,0,'user cancellation is silent');
event('turn/end',{reason:{kind:'interrupted'}});assert.equal(feed.snapshot().items.length,0,'synthetic recovery is silent');
event('turn/end',{reason:{kind:'completed'}},{header:{id:'child',origin:'subagent'}});assert.equal(feed.snapshot().items.length,0,'child completion does not flood parent UI');
event('approval/asked',{id:'child-approval'},{header:{id:'child',origin:'subagent'}});assert.equal(feed.snapshot().items[0].kind,'permission','child waits still require the user');
for(let i=0;i<50;i++)event('turn/end',{reason:{kind:'completed'}},{header:{id:'t-'+i}});
assert.equal(feed.snapshot().items.length,32);
now+=120000;assert.equal(feed.snapshot().items.length,0,'old notices expire instead of replaying after sleep');
feed.enabled=false;event('turn/end',{reason:{kind:'error'}});feed.enabled=true;assert.equal(feed.snapshot().items.length,0);

const home=await mkdtemp(resolve('.build/notifications-'));
function install(){const hooks={};const notifications=installNotifications({on(name,fn){hooks[name]=fn;}},home);return {notifications,hooks};}
let live=install();assert.equal((await live.notifications.snapshot()).enabled,true);
live.hooks['session/event'](session,{type:'turn/end',seq:1,data:{reason:{kind:'completed'}}});
assert.equal((await live.notifications.snapshot()).items.length,1);
await live.notifications.save(false);assert.equal((await live.notifications.snapshot()).items.length,0);
assert.equal(JSON.parse(await readFile(join(home,'desktop-notifications.json'))).enabled,false);
live=install();assert.equal((await live.notifications.snapshot()).enabled,false,'preference persists per connection home');
await live.notifications.save(true);assert.equal((await live.notifications.snapshot()).items.length,0,'restart/reenable never replays old notices');
await writeFile(join(home,'desktop-notifications.json'),'broken');
live=install();assert.equal((await live.notifications.snapshot()).enabled,false);assert((await live.notifications.snapshot()).warning);
await live.notifications.save(true);assert.equal((await live.notifications.snapshot()).warning,null);
console.log('PASS notifications: live-event dedup, resolved waits, cancellation, subagent suppression, bounded TTL, metadata-only feed, independent durable preference, corrupt config recovery');
